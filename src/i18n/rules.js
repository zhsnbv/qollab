// Правила для строк, которых в словаре нет и быть не должно.
//
// Счётчики, даты и статусы вида «318204411: В работе» собираются из данных,
// поэтому уникальных вариантов сотни: «102 публикации», «1020 публикаций»,
// «332 публикации». Держать их в словаре — значит переводить одно и то же
// слово триста раз и ловить промах на каждом новом числе. Здесь вместо этого
// разбирается форма строки, а переводится только слово.

// Русские числительные меняют форму существительного, казахские — нет:
// после числа всегда единственное число.
const UNITS = [
  [/^(.+?)\s(подписчик|подписчика|подписчиков)$/, 'жазылушы'],
  [/^(.+?)\s(публикация|публикации|публикаций)$/, 'жарияланым'],
  [/^(.+?)\s(участник|участника|участников)$/, 'қатысушы'],
  [/^(.+?)\s(организатор|организатора|организаторов)$/, 'ұйымдастырушы'],
  [/^(.+?)\s(сотрудник|сотрудника|сотрудников)$/, 'қызметкер'],
  [/^(.+?)\s(день|дня|дней)$/, 'күн'],
  [/^(.+?)\s(час|часа|часов)$/, 'сағат'],
  [/^(.+?)\s(минуту|минуты|минут)$/, 'минут'],
  [/^(.+?)\s(секунду|секунды|секунд)$/, 'секунд'],
  [/^(.+?)\s(сообщение|сообщения|сообщений)$/, 'хабарлама'],
  [/^(.+?)\s(файл|файла|файлов)$/, 'файл'],
  [/^(.+?)\s(вложение|вложения|вложений)$/, 'тіркеме'],
  [/^(.+?)\s(встреча|встречи|встреч)$/, 'кездесу'],
  [/^(.+?)\s(задача|задачи|задач)$/, 'міндет'],
  [/^(.+?)\s(канал|канала|каналов)$/, 'арна'],
  [/^(.+?)\s(контакт|контакта|контактов)$/, 'контакт'],
];

export const MONTHS = {
  'января': 'қаңтар', 'февраля': 'ақпан', 'марта': 'наурыз', 'апреля': 'сәуір',
  'мая': 'мамыр', 'июня': 'маусым', 'июля': 'шілде', 'августа': 'тамыз',
  'сентября': 'қыркүйек', 'октября': 'қазан', 'ноября': 'қараша', 'декабря': 'желтоқсан',
};
export const MONTHS_SHORT = {
  'янв': 'қаң', 'фев': 'ақп', 'мар': 'нау', 'апр': 'сәу', 'мая': 'мам', 'май': 'мам',
  'июн': 'мау', 'июл': 'шіл', 'авг': 'там', 'сен': 'қыр', 'сент': 'қыр',
  'окт': 'қаз', 'ноя': 'қар', 'дек': 'жел',
};
export const WEEKDAYS = {
  'понедельник': 'дүйсенбі', 'вторник': 'сейсенбі', 'среда': 'сәрсенбі',
  'четверг': 'бейсенбі', 'пятница': 'жұма', 'суббота': 'сенбі', 'воскресенье': 'жексенбі',
};
export const WEEKDAYS_SHORT = {
  'пн': 'дс', 'вт': 'сс', 'ср': 'ср', 'чт': 'бс', 'пт': 'жм', 'сб': 'сн', 'вс': 'жк',
};

const WEEKDAYS_BY_NAME = new Set(Object.keys(WEEKDAYS));

// Сокращение месяца внутри строки: «17 мар 09:30 – 13:00»
const months = (rest) => rest.replace(
  // \b в JS считает границей только латиницу, поэтому рамки задаём явно
  /(?<=^|\s)(янв|фев|мар|апр|мая|май|июн|июл|авг|сент|сен|окт|ноя|дек)(?=\s|$)/g,
  (m) => MONTHS_SHORT[m] || m,
);

// Порядок важен: сначала самые узкие формы, потом общие.
export function applyRules(ru, t) {
  // «12 февраля - четверг», «6 августа - понедельник»
  const full = /^(\d{1,2})\s([а-яё]+)\s-\s([а-яё]+)$/.exec(ru);
  if (full && MONTHS[full[2]] && WEEKDAYS[full[3]]) {
    return `${full[1]} ${MONTHS[full[2]]} - ${WEEKDAYS[full[3]]}`;
  }
  // «11 авг», «3 сент»
  const short = /^(\d{1,2})\s([а-яё]{3,4})$/.exec(ru);
  if (short && MONTHS_SHORT[short[2]]) return `${short[1]} ${MONTHS_SHORT[short[2]]}`;

  // «19.06.2026 в 14:55» — в казахском предлог не нужен, хватает запятой
  const at = /^(.+)\sв\s(\d{1,2}:\d{2})$/.exec(ru);
  if (at) return `${at[1]}, ${at[2]}`;

  // «318204411: В работе», «АО «АЭК»: Открыта» — переводим только статус
  const status = /^(.+?):\s(.+)$/.exec(ru);
  if (status) {
    const tail = t(status[2]);
    if (tail !== status[2]) return `${status[1]}: ${tail}`;
  }

  // «Ср 08:30», «Понедельник, 17 мар 09:30 – 13:00» — день недели впереди,
  // остальное (числа, время) в переводе не нуждается.
  const day = /^([А-Яа-яЁё]+)([,\s].*)$/.exec(ru);
  if (day) {
    const name = t(day[1]);
    if (WEEKDAYS_BY_NAME.has(day[1].toLowerCase()) || WEEKDAYS_SHORT[day[1].toLowerCase()]) {
      return name + months(day[2]);
    }
  }

  // Сокращения в списках чатов и звонков: «5 ч», «12 мин»
  const abbr = /^(\d+)\s(ч|мин|сек|дн)$/.exec(ru);
  if (abbr) return `${abbr[1]} ${{ 'ч': 'сағ', 'мин': 'мин', 'сек': 'сек', 'дн': 'күн' }[abbr[2]]}`;

  for (const [re, word] of UNITS) {
    const m = re.exec(ru);
    if (m) return `${m[1]} ${word}`;
  }
  return null;
}
